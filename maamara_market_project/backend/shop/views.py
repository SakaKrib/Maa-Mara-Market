class WishlistAPIView(APIView):
    permission_classes = [IsAuthenticatedOrVisitor]

    def get_actor(self, request):
        """Identify if it's a user or visitor"""
        if request.user and request.user.is_authenticated:
            return {
                "user": request.user,
                "visitor_id": None,
                "actor_type": "user",
                "actor_name": request.user.username
            }
        else:
            visitor_id = request.COOKIES.get("visitorId")
            if not visitor_id:
                visitor_id = str(uuid.uuid4())
            return {
                "user": None,
                "visitor_id": visitor_id,
                "actor_type": "visitor",
                "actor_name": f"Guest ({visitor_id[:8]})"
            }

    def get(self, request):
        """
        ✅ Get all wishlist items for logged-in user or visitor.
        """
        actor = self.get_actor(request)

        wishlist_items = Wishlist.objects.filter(
            user=actor["user"],
            visitor_id=actor["visitor_id"]
        ).select_related("item")

        # get related Item objects
        items = [w.item for w in wishlist_items]

        serializer = ItemSerializer(items, many=True)

        response = Response({
            "success": True,
            "count": len(items),
            "items": serializer.data
        })

        # ✅ Set visitor cookie if not set yet
        if not request.COOKIES.get("visitorId") and not actor["user"]:
            response.set_cookie(
                "visitorId",
                actor["visitor_id"],
                httponly=True,
                secure=False,
                samesite="Lax",
                max_age=30*24*3600,
            )

        return response

    @transaction.atomic
    def post(self, request, pk):
        """
        Add item to wishlist (user or visitor) and increment item.like only once per actor.
        """
        pk = sanitize(pk)
        item = get_object_or_404(Item, pk=pk)
        actor = self.get_actor(request)

        # --- Prevent duplicate wishlist for same actor ---
        wishlist, created = Wishlist.objects.get_or_create(
            item=item,
            user=actor["user"],
            visitor_id=actor["visitor_id"],
        )

        if created:
            # ✅ Increment item.like atomically
            Item.objects.filter(pk=item.pk).update(likes=F("likes") + 1)
            item.refresh_from_db(fields=['likes'])

            message = "Item added to wishlist"

            # --- One canonical activity event ---
            # The serializer renders "You ..." for the actor and
            # "A customer ..." for other audiences.
            ActivityLog.objects.create(
                user=actor["user"],
                actor_type=actor["actor_type"],
                action="item_added_to_wishlist",
                item=item,
                description=f"A customer added {item.name} to their wishlist.",
                related_url=f"/item/{item.id}/"
            )

            # --- Vendor notification ---
            if item.vendor and item.vendor.user:
                Notification.objects.create(
                    user=item.vendor.user,
                    title="Item added to wishlist",
                    message=f"A customer added {item.name} to their wishlist.",
                    url=f"/item/{item.id}/"
                )

            # --- Admin notifications ---
            superadmins = User.objects.filter(is_superuser=True)
            for admin in superadmins:
                Notification.objects.create(
                    user=admin,
                    title="Item added to wishlist",
                    message=f"A customer added {item.name} to their wishlist.",
                    url=f"/admin-item/vendorDashboard/items/{item.id}/"
                )

        else:
            message = "Item already in wishlist"

        response = Response({
            "success": True,
            "message": message,
            "wishlist_id": wishlist.id,
            "visitor_id": actor["visitor_id"]
        })

        # ✅ Set visitorId cookie if needed
        if not request.COOKIES.get("visitorId") and not actor["user"]:
            response.set_cookie(
                "visitorId",
                actor["visitor_id"],
                httponly=True,
                secure=False,
                samesite="Lax",
                max_age=30*24*3600,
            )

        return response


    @transaction.atomic
    def delete(self, request, pk):
        """
        Remove item from wishlist (user or visitor).
        """
        pk = sanitize(pk)
        item = get_object_or_404(Item, pk=pk)
        actor = self.get_actor(request)

        wishlist_qs = Wishlist.objects.filter(
            item=item,
            user=actor["user"],
            visitor_id=actor["visitor_id"]
        )

        if wishlist_qs.exists():
            wishlist_qs.delete()
            # One canonical activity event for the wishlist change.
            ActivityLog.objects.create(
                user=actor["user"],
                actor_type=actor["actor_type"],
                action="item_removed_from_wishlist",
                item=item,
                description=f"A customer removed {item.name} from their wishlist.",
                related_url=f"/item/{item.id}/"
            )

            # Notifications
            if item.vendor and item.vendor.user:
                Notification.objects.create(
                    user=item.vendor.user,
                    title="Wishlist Update",
                    message=f"A customer removed {item.name} from their wishlist.",
                    url=f"/item/{item.id}/"
                )

            for admin in User.objects.filter(is_superuser=True):
                Notification.objects.create(
                    user=admin,
                    title="Wishlist Update",
                    message=f"A customer removed {item.name} from their wishlist.",
                    url=f"/admin-item/vendorDashboard/items/{item.id}/"
                )

            return Response({"success": True, "message": "Item removed from wishlist"})
        else:
            return Response({"success": False, "message": "Item not found in wishlist"}, status=404)




