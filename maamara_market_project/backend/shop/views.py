FAQ_ALLOWED_TAGS = [
    "p", "br", "strong", "b", "em", "i", "u", "s",
    "h2", "h3", "h4", "ul", "ol", "li", "blockquote", "a",
]
FAQ_ALLOWED_ATTRIBUTES = {
    "a": ["href", "title"],
}
FAQ_ALLOWED_PROTOCOLS = ["http", "https", "mailto"]


def sanitize_rich_text(value):
    """Allow only safe formatting generated by the FAQ editor."""
    if not isinstance(value, str):
        return ""
    return bleach.clean(
        value,
        tags=FAQ_ALLOWED_TAGS,
        attributes=FAQ_ALLOWED_ATTRIBUTES,
        protocols=FAQ_ALLOWED_PROTOCOLS,
        strip=True,
    )


def sanitize(value):
    if isinstance(value, str):
        return bleach.clean(value)
    return value


